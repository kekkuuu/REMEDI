{{--
    The branded wait that covers the page while the dashboard body is fetched.

    Presented as a floating card over a dimmed page, borrowing the app's own
    modal language (.remedi-modal's scrim and panel shadow) so it reads as the
    same kind of object as the logout and confirm dialogs rather than a second
    invented style.

    It is NOT a real dialog: no role="dialog", no aria-modal, no focus trap.
    Nothing here needs answering -- it is a status that happens to be centred,
    and trapping focus in it would strand a keyboard user for ten seconds. The
    failure panel below has real buttons, and they are reachable by Tab because
    of that choice.

    Everything is driven by classes on #dashboardRoot so the shell script can
    move between states without rebuilding the markup.
--}}
