                     that entire window the dev server cannot serve anything
                     else -- including a 278KB PNG. Measured: logo.png, a
                     static file, took 2.83s and landed at the exact moment the
                     dashboard request finished, i.e. just as this loader was
                     being destroyed. The ring spun empty for the whole wait.

                     It looked fine on localhost only because the browser had
                     the file cached from the sidebar. On 127.0.0.1 -- a
                     DIFFERENT ORIGIN with its own empty cache, the same two-
                     hosts trap that bit the cached route URLs -- there was
                     nothing to fall back on and the logo simply never
                     appeared.

                     A loading screen must not depend on a request to the
                     server it is waiting for. logo-mark.webp is a 160px
                     derivative of logo.png (7.6KB, ~10KB inlined) generated by
                     `php artisan logo:mark` -- regenerate it if logo.png ever
                     changes, or this will quietly show the old artwork.

                     width/height match the CSS so the ring cannot reflow.
                     alt="" because the mark is decorative here: the heading
                     beside it already says what is happening. --}}
